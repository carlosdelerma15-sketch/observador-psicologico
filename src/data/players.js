// Helper: agrupar jugadoras por posición
export function getPlayersByPosition() {
  const groups = {};
  for (const pos of Object.values(POSITIONS)) {
    groups[pos] = players.filter((p) => p.position === pos);
  }
  return groups;
}

// Helper: obtener jugadora por ID
export function getPlayerById(id) {
  return players.find((p) => p.id === id) || null;
}

// Helper: obtener iniciales para avatar placeholder
export function getInitials(name) {
  return name
    .split(' ')
    .map((w) => w[0])
    .slice(0, 2)
    .join('')
    .toUpperCase();
}
